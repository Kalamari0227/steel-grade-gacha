import { spawn } from 'node:child_process';
import fs from 'node:fs';
import fsp from 'node:fs/promises';
import { root, evidenceRoot } from './paths.mjs';
import { sha } from './app.mjs';
const [name,command,...args]=process.argv.slice(2);
if(!name||!command)throw Error('Usage: node tests/helpers/run.mjs evidence-name command ...args');
await fsp.mkdir(evidenceRoot,{recursive:true});
const started=new Date().toISOString();
const hashes={};for(const file of ['src/app_tpl.html','src/build.sh','src/pwa_head.txt','src/pwa_body.txt','index.html'])hashes[file]=sha(await fsp.readFile(`${root}/${file}`));
const log=fs.createWriteStream(`${evidenceRoot}/${name}.log`);
const child=spawn(command,args,{cwd:root,env:{...process.env,SGG_REPORT:`${evidenceRoot}/${name}.json`,SGG_RUN_ID:`${name}-${Date.now()}`},stdio:['ignore','pipe','pipe']});
child.stdout.pipe(log);child.stderr.pipe(log);
const exitCode=await new Promise((resolve,reject)=>{child.on('error',reject);child.on('exit',resolve);});
await new Promise(resolve=>log.end(resolve));
const after={};for(const file of Object.keys(hashes))after[file]=sha(await fsp.readFile(`${root}/${file}`));
const reportPath=`${evidenceRoot}/${name}.json`;
let report=null;try{await fsp.access(reportPath);report=reportPath;}catch(error){if(error.code!=='ENOENT')throw error;}
await fsp.writeFile(`${evidenceRoot}/${name}-receipt.json`,JSON.stringify({command:[command,...args],cwd:root,started,ended:new Date().toISOString(),exitCode,beforeHashes:hashes,afterHashes:after,log:`${evidenceRoot}/${name}.log`,report},null,2));
console.log(JSON.stringify({name,exitCode,log:`${evidenceRoot}/${name}.log`}));
process.exitCode=exitCode;
